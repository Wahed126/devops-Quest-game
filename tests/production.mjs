import { preview } from 'vite';
import { chromium } from '@playwright/test';
import { launchOptions } from './browser-config.mjs';
import assert from 'node:assert/strict';
const base=process.env.QUEST_BASE_PATH||'/';
const server=await preview({base,preview:{host:'127.0.0.1',port:4173,strictPort:true}});
let browser;
try{
 browser=await chromium.launch(launchOptions);
 const startUrl=`http://127.0.0.1:4173${base}`;
 // A missing/cached entry bundle must leave a usable page with a recovery path.
 const stalled=await browser.newPage();
  await stalled.route('**/assets/index-*.js',route=>route.abort());
 await stalled.goto(`${startUrl}?v=outdated`);
 assert.equal(await stalled.locator('#startup').isVisible(),true);
 assert.equal(await stalled.locator('#reload-game').isVisible(),true);
 await stalled.unroute('**/assets/index-*.js');
 await Promise.all([stalled.waitForURL(url=>url.searchParams.get('v')!=='outdated'),stalled.locator('#reload-game').click()]);
 await stalled.locator('#new-game:enabled').waitFor();
 assert.notEqual(new URL(stalled.url()).searchParams.get('v'),'outdated','Retry requests a fresh document');
 await stalled.close();
 const noScript=await browser.newPage({javaScriptEnabled:false});
 await noScript.goto(startUrl);
 assert.equal(await noScript.locator('#startup').isVisible(),true);
 assert.match(await noScript.locator('noscript').textContent(),/Enable JavaScript/);
 await noScript.close();
 const page=await browser.newPage({viewport:{width:1280,height:720}}),errors=[];
 page.on('pageerror',e=>errors.push(String(e)));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
 const failedRequests=[];page.on('response',response=>{if(response.status()>=400)failedRequests.push(`${response.status()} ${response.url()}`);});
 const response=await page.goto(startUrl);assert.equal(response.status(),200);
 await page.locator('#new-game:enabled').waitFor();await page.locator('#new-game').click();await page.locator('#skip-dialogue').click();
 await page.keyboard.down('d');await page.waitForTimeout(2050);await page.keyboard.up('d');await page.keyboard.press('e');await page.locator('#command-input').waitFor();
 await page.locator('#command-input').focus();await page.keyboard.type('cat /opt/beacon/config/beacon.conf',{delay:20});assert.equal(await page.locator('#command-input').inputValue(),'cat /opt/beacon/config/beacon.conf');await page.locator('#command-input').press('Enter');
 assert.match(await page.locator('#terminal-output').textContent(),/BEACON_CHANNEL=aurora/);
 await page.locator('#channel-input').fill('aurora');await page.locator('#channel-form button').click();assert.match(await page.locator('#mission-feedback').textContent(),/beacon remembers/);
 await page.locator('#modal-layer').waitFor({state:'hidden',timeout:5000});
 assert.equal(await page.locator('#hud').isVisible(),true,'Successful tuning automatically returns to gameplay');
 assert.equal(await page.evaluate(()=>typeof window.__quest),'undefined','Production omits development instrumentation');assert.deepEqual(errors,[]);assert.deepEqual(failedRequests,[],'Production assets load beneath the configured base path');
 console.log('PASS: blocked bundle shows a visible loading/retry screen; retry recovers with a fresh URL; JavaScript-disabled guidance is visible; production assets, typed first-mission commands, and automatic return after tuning work; no runtime errors or development instrumentation.');
}finally{await browser?.close();await new Promise(resolve=>server.httpServer.close(resolve));}
